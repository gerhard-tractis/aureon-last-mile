export interface OrderSpec {
  group: ScenarioGroup;
  sequence: number;
  operatorId: string;
  orderNumber: string;
  /** Package statuses to create. The order's status is derived from these. */
  packageStatuses: string[];
  customerName?: string;
  comuna?: string;
  deliveryDate?: string;
  importedVia?: string;
  dispatchGuideUrl?: string | null;
  /** The CARGA this order belongs to — matches manifests.external_load_id. */
  externalLoadId?: string | null;
  /** Which client of the operator the order belongs to (Easy, Paris, …). */
  tenantClientId?: string | null;
  /** Where the order is collected from. */
  pickupPointId?: string | null;
  retailerName?: string;
}

export interface CreatedOrder {
  orderId: string;
  orderNumber: string;
  packageIds: string[];
}

/**
 * Resolve a QA login user by email.
 *
 * Several tables reference `public.users` rather than `public.drivers` —
 * notably `pickup_routes.driver_id`, `dock_batches.created_by`,
 * `dock_scans.scanned_by`, `reception_scans.scanned_by` and
 * `route_receptions.delivered_by`. Their ids are generated by
 * create-qa-users.sh rather than fixed, so scenarios look them up by the
 * stable thing: the email.
 *
 * Returns null when the QA users have not been created yet, so a scenario can
 * skip rather than fail with a foreign-key violation.
 */
export async function resolveUserId(
  db: SeedClient,
  email: string,
): Promise<string | null> {
  const rows = await db.query<{ id: string }>(
    'SELECT id FROM public.users WHERE email = $1 AND deleted_at IS NULL LIMIT 1',
    [email],
  );
  return rows[0]?.id ?? null;
}

